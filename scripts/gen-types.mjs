// Regenerates packages/protocol from the Rust types in crates/omni-core.
// ts-rs exports one file per type while running the crate tests.
import { execSync } from "node:child_process";
import { readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "packages/protocol/src/generated");

rmSync(out, { recursive: true, force: true });
execSync("cargo test -p omni-core --quiet export_bindings", { cwd: root, stdio: "inherit" });

const names = readdirSync(out)
  .filter((f) => f.endsWith(".ts"))
  .map((f) => f.slice(0, -3))
  .sort();
const lines = names.map((n) => `export type { ${n} } from "./generated/${n}";`);
lines.push(`export type { JsonValue } from "./generated/serde_json/JsonValue";`);
writeFileSync(
  join(root, "packages/protocol/src/index.ts"),
  `// Generated by scripts/gen-types.mjs. Do not edit.\n${lines.join("\n")}\n`,
);
console.log(`protocol: ${names.length} types`);
